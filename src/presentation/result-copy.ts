export type ResultCopyKey = keyof typeof copy.en;

export function resultCopy(language: Language, key: ResultCopyKey, variables?: Record<string, string | number>) {
  const template = copy[language][key];
  if (!template?.trim()) return `⚠ Translation unavailable: ${key}`;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables?.[name] ?? `{${name}}`));
}

export function resultCopyKeys(): ResultCopyKey[] {
  return Object.keys(copy.en) as ResultCopyKey[];
}

export function missingResultCopy(language: Language) {
  return resultCopyKeys().filter((key) => !copy[language][key]?.trim());
}
